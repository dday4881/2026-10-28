"""실습 02: AUC에는 0/1 판정이 아니라 실패 클래스의 연속 점수를 넣습니다."""
from sklearn.metrics import roc_auc_score, roc_curve
# 정상적인 원리 예제 4건입니다. 수업용 파일의 test 결과가 아닙니다.
y = [0, 0, 1, 1] # 세로축
score = [0.10, 0.40, 0.35, 0.80]
# TODO B02: roc_auc_score에 실제값과 연속 점수를 넣으세요.
auc = roc_auc_score(y, score) # auc 함수에 roc값 + auc 함수값 + score에 실제 정답 y를 괄호 없이 입력 할 수 없어서 (y,score)라고 입력
# TODO 끝
fpr, tpr, thresholds = roc_curve(y, score) #thresholds 는 임계값
print("FPR:", fpr.round(2).tolist()) # round 함수 안 괄호속 숫자 n = 소숫점 n번째 자리 까지 표현
print("TPR:", tpr.round(2).tolist()) # tolist 함수는 파이썬 리스트 형태로 눈에 보기 좋게 정리 표현
print(f"AUC: {auc:.2f}")
print("양성 점수 0.35·0.80과 음성 점수 0.10·0.40을 네 번 비교하세요.")

""" 출력 결과 값
FPR: [0.0, 0.0, 0.5, 0.5, 1.0]
TPR: [0.0, 0.5, 0.5, 1.0, 1.0]
AUC: 0.75
양성 점수 0.35·0.80과 음성 점수 0.10·0.40을 네 번 비교하세요. """

#강사님의 힌트 풀이: AUC가 왜 0.75(75%)일까?

#AUC는 쉽게 말해 "실제 실패(1)인 데이터의 점수가 실제 성공(0)인 데이터의 점수보다 높게 잘 정렬되어 있는가?"를 확률로 나타낸 것입니다.
#실제 실패(양성) 점수 2개와 실제 성공(음성) 점수 2개를 하나씩 총 4번 1:1 맞대결(비교)을 시켜보는 원리입니다.
#1. 첫 번째 실패(0.35) vs 첫 번째 성공(0.10) ➡️ 0.35가 더 높음! (성공 / +1점)
#2. 첫 번째 실패(0.35) vs 두 번째 성공(0.40) ➡️ 0.35가 더 낮음! (실패 / +0점)
#3. 두 번째 실패(0.80) vs 첫 번째 성공(0.10) ➡️ 0.80이 더 높음! (성공 / +1점)
#4. 두 번째 실패(0.80) vs 두 번째 성공(0.40) ➡️ 0.80이 더 높음! (성공 / +1점)
#• 총 4번의 비교 중 3번 모델이 점수를 올바르게(실패 데이터의 점수를 더 높게) 부여했습니다.
#• 즉, 3 / 4 = 0.75 (75%)라는 AUC 결과가 도출되는 것입니다.
